def kit_ss(x):
    x = min(1.0, max(0.0, x))
    return x * x * (3 - 2 * x)


def _shot(tl, t):
    for s in tl["shots"]:
        if s["start"] <= t < s["end"]:
            return s
    return tl["shots"][-1]


