def copy_blink(story, tl, t):
    """The copy blinks only when I blink, LAG later."""
    cast = list(story.get("cast", {}))
    if "me" not in cast:
        return 0.0
    return acting.state(tl, "me", t - LAG, cast.index("me"))["blink"]


def pose_copy(story, tl, t, ctx):
    c = ctx.get("copy")
    if c is None:
        return
    keys = tl["acting"].get("copy")
    if not keys:
        c.pose(0, 0, 0, 0, hidden=True)
        return
    s = acting.state(tl, "copy", t, 0)
    blink = copy_blink(story, tl, t) if acting._switch(keys, "blink", t, True) else 0.0
    # "stride" holds the legs apart while it stands (frozen mid-step, one foot up), eased like any number
    legs = s["legs"] + math.radians(acting._held(keys, "stride", t, 0.0))
    x, y, z, yaw = s["x"], s["y"], s["z"], s["yaw"]
    at_ = cue_at(tl, "copyattach", t)
    if at_.get("on") and ctx.get("carry"):   # it stands in the pane the maze guy carries
        cx, cy, cz, cyaw = ctx["carry"]
        side, ahead = at_.get("off", [0.0, 0.45])
        x, y, z = cx + ahead * math.sin(cyaw) + side * math.cos(cyaw), cy - ahead * math.cos(cyaw) + side * math.sin(cyaw), cz
        yaw = cyaw + math.radians(at_.get("yaw", 0))
    c.pose(x, y, z, yaw, legs, s["arms"], s["arms_side"], s["head_yaw"], s["head_pitch"],
           s["lean"], s["bob"], s["expr"], s["mouth"], s["look"], blink, s["hidden"])
    # its face is late on its own head (creature pass 3): it points where the head pointed LAG ago and slides round
    # after it. In head terms that's the opposite way on the mirrored rig, and the UVs run once round (u = angle / 2 pi)
    lag = story.get("face_lag", LAG)
    d = face_lag_offset(tl, t, float(lag)) if lag else 0.0
    if getattr(c, "face_map", None) is not None:
        c.face_map.inputs["Location"].default_value[0] = d / (2 * math.pi)
    # the sockets are cut where the face sits at rest, so while the face is off its place the plain head shows
    moving = abs(d) > math.radians(0.5)
    update_sockets(c, s["expr"], s["mouth"], blink, force_plain=moving)


def apply_bow(tl, t, who):
    """Acting key "bow": degrees the torso bends forward at the hips (R6 has no knees, so a duck is a bow). The arms
    keep hanging straight down, and the coat's panels stay with the legs."""
    keys = tl["acting"].get(who)
    if not keys:
        return
    bow = math.radians(acting._held(keys, "bow", t, 0.0))
    torso = bpy.data.objects.get(f"{who}.torso")
    if torso is None:
        return
    torso.rotation_euler = (bow, 0, 0)
    for sx in (-1, 1):
        arm = bpy.data.objects.get(f"{who}.arm{sx}")
        if arm is not None and bow:
            e = arm.rotation_euler
            arm.rotation_euler = (e[0] - bow, e[1], e[2])


def link_lights(kit, story, ctx):
    """Once, on the first frame (the cast exists by then): story "light_only": {light: [object names]} makes that
    light reach only those objects (Blender's light linking)."""
    if ctx.get("linked"):
        return
    ctx["linked"] = True
    for nm, names in story.get("light_only", {}).items():
        col = bpy.data.collections.new(f"{nm} only")
        for on in names:   # an exact name, or "who.*" for every mesh of a character
            obs = ([o for o in bpy.data.objects if o.type == "MESH" and o.name.startswith(on[:-1])] if on.endswith("*")
                   else [bpy.data.objects.get(on)])
            for ob in obs:
                if ob is not None and ob.name not in col.objects:
                    col.objects.link(ob)
        for co in col.collection_objects:
            co.light_linking.link_state = "INCLUDE"
        kit.LIGHTS[nm]["obj"].light_linking.receiver_collection = col


def set_wet(story, wet):
    """Tasha's coat (and the copy's: they share it) soaked: darker and glossier."""
    tasha = story.get("cast", {}).get("tasha")
