"""Mirror Maze (ep14): the last weekend of a travelling fair in the rain, half packed up, and the mirror maze, the
only ride still lit. Built from kit.py's parts (batch 2, story 2; nothing here is shared with another story's set).
Nothing in the set has text: no lettering, logos, signs, numbers or badges.

This is the start of the set, built for the creature test still (the scare's end, out on the open ground): the field
with its duckboards and puddles, the crew's caged worklight on a low tripod, and the maze's front behind them, with
its arch, its two rows of round lilac-white bulbs and one more row along the roofline, its plain geometric panels and
the first glass panes inside the arch. The rest of the fair (the truck, the bumper cars, the fry van, the dark big
wheel, the maze's inside on both trips) comes with the build.

Coordinates: the field is z = 0 and the duckboards' top is BOARD_Z. The maze's front faces -y at y = MAZE_Y, its
platform is PLAT_Z up, and its arch is centred on x = ARCH_X. Facing the maze is yaw 180 (a character faces -y at 0).

THE COPY (the brief's continuity list). One model, built once in build() and posed every frame in animate():
- It's Tasha's own cast spec, generated by copy_spec() (never a second hand-made spec), and mirrored left to right as a
  whole by a negative x scale on its root. So exactly three things show the flip: her swoop fringe, her lopsided
  smirk (the face texture flips with the mesh) and her handedness. Nothing else on her is one-sided.
- Its eyes are faces.py's "mirror" style: Tasha's own eye outline and size, near-black to the edge, no pupil and no
  glint, with her brows and mouth. When its mouth opens it opens onto the same black ("mouth_inside"). matte_eyes() makes its head material dead matte wherever the texture is that
  black, so no light glints off the eyes either (a glossy black oval reads as sunglasses). The eyes, and the mouth
  when it opens, are also real sockets cut into its head along those exact outlines (build_sockets), so they read
  as holes, not paint: matte skin walls whose top edge catches the light from below, and a void at the bottom. A
  blink or closed eyes switch the cut off. A story can turn them off with "sockets": false.
- Its face is late on its own head (creature pass 3): the drawn face points where the head pointed LAG ago, so when
  the head turns, the face stays behind and slides round after it with the head's own ease. While it's off its place
  the sockets give way to the plain head, and come back when it settles. "face_lag": seconds (default LAG) or false.
- It blinks only when I blink, LAG later, never on its own. It makes no sound (sound.py never sees it: it's not cast).
- Its keys ("copy" in the acting) are in the rig's own local terms, so on screen every left and right comes out
  mirrored: arms [left, right] swap sides, a head yaw turns the other way. Its pos and yaw are world terms. My
  reflection is therefore my own keys verbatim, LAG later, with pos and yaw reflected across the glass plane.

Acting keys read here (acting.py ignores them): for the copy, "stride": degrees the legs are held apart while it
stands (+ = its left leg forward), for a freeze mid-step and the replay's step; for anyone, "bow": degrees the torso
bends forward at the hips (the duck behind the truck), with the arms kept hanging.

Story keys read here (all optional):
- "looks": {shot id: {...}} one shot's own lights. "work", "rim", "rim2", "bounce", "kick", "face", "hair": [pos, aim, watts,
  size or cone degrees?, colour?] puts that light exactly there for the shot (the worklight's body stays on its
  stand); "maze", "inside", "wash": gains on the maze's glow, its inside and the bulbs' glow on the facade;
  "bulbs": a gain on the bulbs' own brightness. A light a shot doesn't name is off, except those three, which stay
  at 1. "face" and "hair" cast no shadows and are meant for "light_only" (the scare's key from below, on the heads).
- "dof": {shot id: [focus metres, f-stop]} depth of field for the shots that ask for it.
- "light_only": {light: [object names]} that light reaches only those objects (e.g. "face" on the heads alone);
  "me.*" is every mesh of a character.
"""

