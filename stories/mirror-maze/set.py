def copy_spec(tasha: dict) -> dict:
    """The copy's spec, always generated from Tasha's: the same blocks, skin, coat, hair and height, with the
    mirror-black eyes. The mirroring itself is done on the model (build_copy)."""
    spec = _copy.deepcopy(tasha)
    # the eyes go black, and an open mouth opens onto the same black (when it copies my gasp: three holes)
    spec["face"] = {**spec.get("face", {}), "eyes": "mirror", "mouth_inside": "#07070a"}
    spec.pop("voice", None)
    return spec


def face_slide(ch):
    """The copy's face can slide round its own head: a mapping between the head's UVs and the face texture (which
    wraps the whole head, skin everywhere outside the face, so it slides with no seam to see). pose_copy() sets it."""
    nt = ch.head_mat.node_tree
    N, L = nt.nodes, nt.links
    uvn = next(n for n in N if n.type == "UVMAP")
    mp = N.new("ShaderNodeMapping")
    mp.vector_type = "POINT"
    L.new(uvn.outputs["UV"], mp.inputs["Vector"])
    L.new(mp.outputs["Vector"], ch.face_tex.inputs["Vector"])
    ch.face_tex.extension = "REPEAT"
    return mp


def head_angle(s):
    """Where the copy's head points in the world (radians): its body's yaw less the neck's, which turns the other
    way on the mirrored rig."""
    return s["yaw"] - s["head_yaw"]


def face_lag_offset(tl, t, lag):
    """How far the copy's face trails its own head (radians, world): where the head pointed `lag` seconds ago, less
    where it points now. 0 while the head holds still."""
    now = acting.state(tl, "copy", t, 0)
    then = acting.state(tl, "copy", max(0.0, t - lag), 0)
    d = head_angle(then) - head_angle(now)
    return (d + math.pi) % (2 * math.pi) - math.pi


def matte_eyes(kit, ch):
    """No glint, glow or reflection in the copy's eyes: wherever its face texture is the eyes' near-black (darker than
    any ink), the head's surface is fully rough and has no specular, so a light can't catch in them."""
    nt = ch.head_mat.node_tree
    N, L = nt.nodes, nt.links
    b = N["Principled BSDF"]
    g = N.new("ShaderNodeGamma")   # back to display values, where the eyes' 10/255 and the ink's 34/255 are apart
    g.inputs["Gamma"].default_value = 1 / 2.2
    L.new(ch.face_tex.outputs["Color"], g.inputs["Color"])
    sep = N.new("ShaderNodeSeparateColor")
    L.new(g.outputs[0], sep.inputs[0])
    m1 = N.new("ShaderNodeMath")
    m1.operation = "MAXIMUM"
    L.new(sep.outputs[0], m1.inputs[0])
    L.new(sep.outputs[1], m1.inputs[1])
    m2 = N.new("ShaderNodeMath")
    m2.operation = "MAXIMUM"
    L.new(m1.outputs[0], m2.inputs[0])
    L.new(sep.outputs[2], m2.inputs[1])
    mask = N.new("ShaderNodeMapRange")   # 1 inside the eyes, 0 elsewhere
    mask.inputs["From Min"].default_value = 0.06
    mask.inputs["From Max"].default_value = 0.085
    mask.inputs["To Min"].default_value = 1.0
    mask.inputs["To Max"].default_value = 0.0
    L.new(m2.outputs[0], mask.inputs["Value"])
    rough = N.new("ShaderNodeMapRange")
    rough.inputs["To Min"].default_value = b.inputs["Roughness"].default_value
    rough.inputs["To Max"].default_value = 1.0
    L.new(mask.outputs["Result"], rough.inputs["Value"])
    L.new(rough.outputs["Result"], b.inputs["Roughness"])
    key = "Specular IOR Level" if "Specular IOR Level" in b.inputs else "Specular"
    spec = N.new("ShaderNodeMapRange")
    spec.inputs["To Min"].default_value = b.inputs[key].default_value
    spec.inputs["To Max"].default_value = 0.0
    L.new(mask.outputs["Result"], spec.inputs["Value"])
    L.new(spec.outputs["Result"], b.inputs[key])


# ---- the copy's sockets: its eyes (and an open mouth) are real holes in its head, not paint. A boolean cuts each
# one exactly along the outline faces.py draws (so never bigger than Tasha's eyes), radially into the head: the walls
# are matte skin, so the light from below catches a thin rim inside the top edge, and the floor is a matte void. The
# cut follows the face: a blink, closed eyes or the angry lid put the uncut head back (the drawn lid shows), and each
# eye size or mouth opening is cut once and kept.
SOCKET_IN = 0.55   # the floor's radius as a share of the head's: the sockets are 0.45 R deep


def _surface(u_px, v_px):
    """A face-texture pixel (x across, y down from the top) -> (angle, z) on the head (rig.head_mesh's mapping)."""
    from blocky import faces as F

    u = (u_px + 0.5) / F.TEX_W
    v = 1.0 - (v_px + 0.5) / F.TEX_H
    b = 0.16
    return 2 * math.pi * u - 1.5 * math.pi, v * (F.HEAD_H - b) + b / 2 - F.HEAD_H / 2


def cutter_mesh(name, cx, cy, rx, ry, n=64):
    """A closed tube from SOCKET_IN * R out past the skin, its section the ellipse (cx, cy, rx, ry) in texture pixels
    taken radially onto the head. Material 0 is the walls, 1 the floor."""
    from blocky import faces as F

    R = F.HEAD_R
    pts = [_surface(cx + rx * math.cos(2 * math.pi * k / n), cy + ry * math.sin(2 * math.pi * k / n)) for k in range(n)]
    verts = [(r * math.cos(a), r * math.sin(a), z) for r in (R * SOCKET_IN, R * 1.35) for a, z in pts]
    fcs = [(k, (k + 1) % n, n + (k + 1) % n, n + k) for k in range(n)]
    fcs += [tuple(range(n))[::-1], tuple(range(n, 2 * n))]
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], fcs)
    me.update()
    for poly in me.polygons:
        poly.material_index = 1 if poly.index == n else 0
    return me


def socket_shapes(expr, open_, blink):
    """What the face texture draws: [(cx, cy, rx, ry)] for the holes, from faces.py's own numbers, or [] when the
    eyes are shut (a blink, closed eyes, the angry lid)."""
    from blocky import faces as F

    s = F.FX1 - F.FX0
    out = []
    if blink <= 0.5 and expr not in ("shut", "squeeze", "soft", "angry"):
        rx = 0.112 * s * (1.28 if expr == "terrified" else 1.2 if expr in ("wide", "scared") else 1.0)
        for side in (-1, 1):
            out.append((F._fx(0.5) + side * 0.22 * s, F._fy(0.42), rx, rx))
    q = round(open_ * 3) / 3
    if q > 0.05 and expr != "blank":
        w = 0.22 * s
        ww = w * (0.55 if expr in ("scared", "wide", "crying", "worried", "terrified", "squeeze") else 0.75)
        out.append((F._fx(0.5), F._fy(0.74), ww / 2, (0.035 + 0.075 * q) * s / 2))
    return out


def dense_head_mesh(name, n=192, arc=8, rings=44):
    """rig.head_mesh's own surface and UVs (the same soft rounded cylinder), sampled finely, so a socket cut into it
    shades as smoothly as Tasha's head. Only the copy's head is swapped for it."""
    from blocky import faces as F

    R, H, b = F.HEAD_R, F.HEAD_H, 0.16
    prof = [(0.0, 0.0)]
    for k in range(arc + 1):
        a = -math.pi / 2 + (math.pi / 2) * k / arc
        prof.append((R - b + b * math.cos(a), b + b * math.sin(a)))
    for k in range(1, rings):
        prof.append((R, b + (H - 2 * b) * k / rings))
    for k in range(arc + 1):
        a = (math.pi / 2) * k / arc
        prof.append((R - b + b * math.cos(a), H - b + b * math.sin(a)))
    prof.append((0.0, H))
    verts, uvs = [], []
    for j in range(n + 1):
        ang = 2 * math.pi * j / n - math.pi / 2 - math.pi
        for r, z in prof:
            verts.append((r * math.cos(ang), r * math.sin(ang), z - H / 2))
            uvs.append((j / n, min(1.0, max(0.0, (z - b * 0.5) / (H - b)))))
    m = len(prof)
    fcs = [(j * m + i, (j + 1) * m + i, (j + 1) * m + i + 1, j * m + i + 1) for j in range(n) for i in range(m - 1)]
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], fcs)
    me.update()
    uv = me.uv_layers.new(name="UVMap")
    for poly in me.polygons:
        poly.use_smooth = True
        for li in poly.loop_indices:
            uv.data[li].uv = uvs[me.loops[li].vertex_index]
    return me


def build_sockets(kit, c):
    headm = bpy.data.objects["copy.headm"]
    dense = dense_head_mesh("copy.head.dense")
    for mat in headm.data.materials:
        dense.materials.append(mat)
    headm.data = dense
    wall = kit.plastic(c.spec["skin"], 0.95, name="copy socket wall", spec=0.1)
    void = pbr(kit, "copy socket void", "#040405", 1.0, spec=0.0)
    c.sockets = {"headm": headm, "dense": dense, "meshes": {(): dense}, "key": (), "wall": wall, "void": void}


def holed_mesh(c, shapes, key):
    """The copy's head with these sockets cut, made once per shape and kept (no live modifier: a head never
    deforms, so each face state is a plain mesh to swap in)."""
    import bmesh

    S = c.sockets
    scene = bpy.context.scene
    tmp = bpy.data.collections.new("socket work")
    scene.collection.children.link(tmp)
    ops = bpy.data.collections.new("socket cutters")
    scene.collection.children.link(ops)
    ob = bpy.data.objects.new("socket head", S["dense"].copy())
    tmp.objects.link(ob)
    cutters = []
    for k, sh in enumerate(shapes):
        me = cutter_mesh(f"socket cutter {k}", *sh)
        me.materials.append(S["wall"])
        me.materials.append(S["void"])
        co = bpy.data.objects.new(f"socket cutter {k}", me)
        ops.objects.link(co)
        cutters.append(co)
    mod = ob.modifiers.new("cut", "BOOLEAN")
    mod.operation, mod.solver, mod.operand_type = "DIFFERENCE", "EXACT", "COLLECTION"
    mod.collection = ops
    mod.material_mode = "TRANSFER"
    dg = bpy.context.evaluated_depsgraph_get()
    dg.update()
    me = bpy.data.meshes.new_from_object(ob.evaluated_get(dg), preserve_all_data_layers=True, depsgraph=dg)
    me.name = f"copy.head.sockets.{len(S['meshes'])}"
    # the rim of each hole stays a crisp edge: no smoothing across skin, wall and void
    names = [m.name if m else "" for m in me.materials]
    bm = bmesh.new()
    bm.from_mesh(me)
    for e in bm.edges:
        fs = e.link_faces
        if len(fs) == 2 and names[fs[0].material_index] != names[fs[1].material_index]:
            e.smooth = False
    for f in bm.faces:
        f.smooth = names[f.material_index] != S["void"].name
    bm.to_mesh(me)
    bm.free()
    for co in cutters:
        md = co.data
        bpy.data.objects.remove(co)
        bpy.data.meshes.remove(md)
    tmp_me = ob.data
    bpy.data.objects.remove(ob)
    bpy.data.meshes.remove(tmp_me)
    bpy.data.collections.remove(ops)
    bpy.data.collections.remove(tmp)
    S["meshes"][key] = me
    return me


def update_sockets(c, expr, open_, blink, force_plain=False):
    S = getattr(c, "sockets", None)
    if S is None:
        return
    shapes = [] if force_plain else socket_shapes(expr, open_, blink)
    key = tuple(tuple(round(v, 2) for v in sh) for sh in shapes)
    if key == S["key"]:
        return
    S["key"] = key
    S["headm"].data = S["meshes"].get(key) or holed_mesh(c, shapes, key)


